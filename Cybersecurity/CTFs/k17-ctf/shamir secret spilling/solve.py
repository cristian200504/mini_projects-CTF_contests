# ── Step 7: CVP/BDD lattice attack ───────────────────────────────────────────
#
# We want C = (c_0..c_7) in Z^8 such that:
#   e_k = centered(R_part[k] + sum_j G[k-j]*c_j, MOD),  |e_k| < B
#
# Build a (8+32+1) x (8+32+1) lattice:
#
# The standard Kannan embedding for CVP:
#   Given lattice basis B and target t, add row (b_1,...,b_n, 0) for basis
#   and row (t, M) for target (M large "tag").
#   LLL finds a short vector close to t.
#
# Our lattice (in 32-dim e-space, parameterised by 8-dim c):
# Generators for the q-ary lattice:
#   For j=0..7:  column j of G's Toeplitz matrix (32-dim vector)
#   For k=0..31: MOD * e_k  (to ensure reduction mod MOD)
# But 8+32=40 generators for 32-dim space... need to build 40x40 matrix.
#
# Actually: work in (8+32)-dim space (c-space + e-space).
# The lattice vector we want: (c_0,..,c_7, e_0,..,e_31)
# where e_k = R_part[k] + sum_j G[k-j]*c_j  (mod MOD, centered).
#
# Lattice basis:
#   Row j (j=0..7):      e_j in c-part,  G-column-j in e-part  (scaled by S)
#   Row 8+k (k=0..31):   0 in c-part,    MOD*e_k in e-part     (scaled by S)
#
# Embedding row:  0 in c-part,  -R_part in e-part (scaled by S),  tag C
#
# Scale S = 1 (don't scale -- the c_j values are O(MOD) and that's fine,
# LLL just needs the target e vector to be shortest).
# 
# Actually with c_j ~ MOD and e_k ~ B, the target vector norm is:
#   sqrt(8*MOD^2 + 32*B^2) ~ sqrt(8)*MOD ~ 2^514
# The "generic" lattice vector has norm ~ sqrt(40)*MOD ~ 2^515
# So the target IS the shortest vector -- LLL should find it!
# 
# We just need S such that the c and e parts balance for LLL's metric.
# Set S = MOD // B so scaled e_k * S ~ B*(MOD/B) = MOD. Balanced!

print("[7] Running lattice attack (CVP embedding)...")

nc = 8   # number of c variables
ne = 32  # number of e variables

S = MOD // B   # ~ 2^239, balance c and e scales

# Toeplitz: T[k][j] = G[k-j] mod MOD for k=0..31, j=0..7
def G_toeplitz(k, j):
    idx = k - j
    return G[idx] if 0 <= idx < len(G) else 0

# Build (nc + ne + 1) x (nc + ne + 1) matrix
dim = nc + ne + 1   # 41

mat = [[0]*dim for _ in range(dim)]

# Rows 0..nc-1: e_j in c-part, Toeplitz column j (scaled) in e-part
for j in range(nc):
    mat[j][j] = 1   # c-part: identity (no scaling needed)
    for k in range(ne):
        mat[j][nc + k] = G_toeplitz(k, j) * S   # e-part scaled

# Rows nc..nc+ne-1: 0 in c-part, MOD*e_k (scaled) in e-part
for k in range(ne):
    mat[nc + k][nc + k] = MOD * S

# Embedding row: 0 in c-part, -R_part*S in e-part, large tag in last col
C_tag = MOD   # tag to identify embedding row
for k in range(ne):
    mat[nc + ne][nc + k] = ((-R_part[k]) % MOD) * S
mat[nc + ne][nc + ne] = C_tag

# Load and reduce
M = IntegerMatrix(dim, dim)
for i in range(dim):
    for j in range(dim):
        M[i, j] = mat[i][j]

print(f"    Lattice dimension: {dim}x{dim}. Running LLL...")
LLL.reduction(M)
print("    LLL done.")

# Extract: find row with last column = ±C_tag
def try_extract(row, sign):
    c_vals = [(sign * row[j]) % MOD for j in range(nc)]
    # Compute e_k = R_part[k] + sum_j G[k-j]*c_vals[j]  mod MOD, centered
    e_vals = []
    for k in range(ne):
        s = R_part[k]
        for j in range(nc):
            s = (s + G_toeplitz(k, j) * c_vals[j]) % MOD
        e_vals.append(centered(s, MOD))
    # Check all |e_k| < B
    if all(abs(e) < B for e in e_vals):
        return c_vals, e_vals
    return None, None

C_found = None
e_found = None
for row_idx in range(dim):
    row = [M[row_idx][j] for j in range(dim)]
    if abs(row[nc + ne]) == C_tag:
        sign = 1 if row[nc + ne] == C_tag else -1
        c_vals, e_vals = try_extract(row, -sign)
        if c_vals is not None:
            C_found = c_vals
            e_found = e_vals
            print(f"    Solution found at row {row_idx}!")
            break
        # try other sign
        c_vals, e_vals = try_extract(row, sign)
        if c_vals is not None:
            C_found = c_vals
            e_found = e_vals
            print(f"    Solution found at row {row_idx} (alt sign)!")
            break

if C_found is None:
    raise RuntimeError("LLL did not find a valid C vector.")

# ── Step 8: Reconstruct Q ─────────────────────────────────────────────────────
