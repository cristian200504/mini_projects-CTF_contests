# ── Helpers ───────────────────────────────────────────────────────────────────

def poly_eval(coeffs, x, mod):
    result, xp = 0, 1
    for c in coeffs:
        result = (result + c * xp) % mod
        xp = xp * x % mod
    return result

def lagrange_interpolation(points, mod):
    n = len(points)
    xs = [p[0] for p in points]
    ys = [p[1] for p in points]
    coeffs = [0] * n
    for i in range(n):
        basis = [1]
        for j in range(n):
            if j == i: continue
            nb = [0] * (len(basis) + 1)
            for k, b in enumerate(basis):
                nb[k+1] = (nb[k+1] + b) % mod
                nb[k]   = (nb[k] - b * xs[j]) % mod
            basis = nb
        denom = 1
        for j in range(n):
            if j != i: denom = denom * (xs[i] - xs[j]) % mod
        scale = ys[i] * pow(denom, mod-2, mod) % mod
        for k in range(len(basis)):
            coeffs[k] = (coeffs[k] + scale * basis[k]) % mod
    return coeffs

def poly_mul(a, b, mod):
    r = [0] * (len(a) + len(b) - 1)
    for i, ca in enumerate(a):
        for j, cb in enumerate(b):
            r[i+j] = (r[i+j] + ca*cb) % mod
    return r

def vanishing_poly(xs, mod):
    p = [1]
    for x in xs:
        p = poly_mul(p, [(-x)%mod, 1], mod)
    return p

def centered(x, mod):
    x %= mod
    return x if x <= mod//2 else x - mod

def verify_Q(Q):
    for x, y in known:
        if poly_eval(Q, x, MOD) != y: return False, "known"
    for x, y in new:
        if poly_eval(Q, x, MOD) != y: return False, "new"
    P_pad = P + [0]*16
    for i in range(32):
        if abs(centered(Q[i]-P_pad[i], MOD)) >= B: return False, f"bound[{i}]"
    return True, "ok"

